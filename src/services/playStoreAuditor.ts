import { PlayStoreAuditItem, ProjectSettings } from '../types';

export class PlayStoreAuditor {
  /**
   * Performs complete automated audit of Google Play Store submission policies
   */
  static runAudit(
    settings: ProjectSettings,
    storeListing: {
      title: string;
      shortDescription: string;
      fullDescription: string;
      privacyPolicyUrl: string;
      accountDeletionUrl: string;
      contactEmail: string;
    }
  ): { items: PlayStoreAuditItem[]; scorePercent: number } {
    const items: PlayStoreAuditItem[] = [];

    // 1. Target SDK 35 Check
    if (settings.targetSdk >= 35) {
      items.push({
        id: 'target_sdk',
        category: 'technical',
        title: 'Target SDK 35 (Android 15)',
        description: `Your app targets API Level ${settings.targetSdk}, fulfilling Google Play's latest requirement.`,
        status: 'passed',
        recommendation: 'Compliant with Google Play August 2025+ submission requirement.',
        linkDoc: 'https://developer.android.com/google/play/requirements/target-sdk',
      });
    } else {
      items.push({
        id: 'target_sdk',
        category: 'technical',
        title: 'Target SDK Outdated',
        description: `Currently targeting API ${settings.targetSdk}. Google Play requires API 35 (Android 15) for new apps.`,
        status: 'failed',
        recommendation: 'Increase targetSdk and compileSdk to 35 in project settings.',
      });
    }

    // 2. Android App Bundle (.aab) format
    items.push({
      id: 'aab_format',
      category: 'technical',
      title: 'App Bundle (.aab) Submission Format',
      description: 'Google Play exclusively requires .aab format for all new app releases (reducing download size by 15-30%).',
      status: 'passed',
      recommendation: 'Always upload .aab generated by ESDY Studio for production tracks.',
    });

    // 3. 16 KB Page Alignment support
    if (settings.enable16KbPageSupport) {
      items.push({
        id: 'page_16kb',
        category: 'technical',
        title: '16 KB Memory Page Size Support',
        description: 'Native libraries (.so) and packaging flags are configured to support 16 KB page sizes required for Android 15 & next-gen devices.',
        status: 'passed',
        recommendation: 'Compliant with Google Play 2025 16KB alignment policy.',
      });
    } else {
      items.push({
        id: 'page_16kb',
        category: 'technical',
        title: '16 KB Memory Page Size Missing',
        description: 'Android 15 introduces 16 KB page sizes. Without alignment, apps with native C/C++ or WebKit libraries may crash.',
        status: 'warning',
        recommendation: 'Enable 16 KB page size support in Project Settings.',
      });
    }

    // 4. Privacy Policy URL
    const hasValidPrivacy =
      storeListing.privacyPolicyUrl.startsWith('https://') &&
      storeListing.privacyPolicyUrl.length > 12;
    if (hasValidPrivacy) {
      items.push({
        id: 'privacy_policy',
        category: 'privacy',
        title: 'HTTPS Privacy Policy URL',
        description: `Valid public HTTPS privacy policy URL provided: ${storeListing.privacyPolicyUrl}`,
        status: 'passed',
        recommendation: 'Ensure your privacy policy explicitly discloses all collected data categories.',
      });
    } else {
      items.push({
        id: 'privacy_policy',
        category: 'privacy',
        title: 'Missing or Invalid Privacy Policy URL',
        description: 'Google Play rejects any app without an active, publicly accessible HTTPS privacy policy URL.',
        status: 'failed',
        recommendation: 'Provide a valid https:// URL leading to your privacy policy.',
      });
    }

    // 5. Account Deletion Requirement (Policy enforced since 2024)
    const hasAccountDeletion =
      storeListing.accountDeletionUrl.startsWith('https://') &&
      storeListing.accountDeletionUrl.length > 12;
    if (hasAccountDeletion) {
      items.push({
        id: 'account_deletion',
        category: 'privacy',
        title: 'Account & Data Deletion URL',
        description: `Web-based deletion request portal configured: ${storeListing.accountDeletionUrl}`,
        status: 'passed',
        recommendation: 'Users must be able to delete their account and associated data from this page without re-installing the app.',
      });
    } else {
      items.push({
        id: 'account_deletion',
        category: 'privacy',
        title: 'Account Deletion Path Required',
        description: 'Apps that allow account creation must provide a web link where users can request account and data deletion.',
        status: 'warning',
        recommendation: 'Set a web URL where users can request account deletion (e.g., https://yourdomain.com/delete-account).',
      });
    }

    // 6. Sensitive Permissions Audit
    const permissions = settings.permissions;
    if (permissions.location) {
      items.push({
        id: 'perm_location',
        category: 'policy',
        title: 'Sensitive Permission: Location Access',
        description: 'ACCESS_FINE_LOCATION and ACCESS_COARSE_LOCATION declared.',
        status: 'info',
        recommendation: 'Google Play requires you to explain in the review console why location is core to user functionality.',
      });
    }

    if (permissions.foregroundService) {
      items.push({
        id: 'perm_fg_service',
        category: 'policy',
        title: 'Foreground Service Types Declaration',
        description: 'Android 14+ requires declaring specific foregroundServiceType in AndroidManifest.xml (e.g. dataSync, mediaPlayback).',
        status: 'warning',
        recommendation: 'Specify exact foregroundServiceType attributes in the Manifest.',
      });
    }

    // 7. Store Listing Title Length (Max 30 chars)
    if (storeListing.title.length > 0 && storeListing.title.length <= 30) {
      // Check for forbidden spam keywords
      const spamWords = ['#1', 'best', 'top', 'free', 'discount', 'download now'];
      const hasSpam = spamWords.some(w => storeListing.title.toLowerCase().includes(w));
      if (!hasSpam) {
        items.push({
          id: 'listing_title',
          category: 'listing',
          title: 'Store Listing App Title (Valid)',
          description: `Title length: ${storeListing.title.length}/30 characters. No prohibited promotional terms detected.`,
          status: 'passed',
          recommendation: 'Keep title focused on brand and primary function.',
        });
      } else {
        items.push({
          id: 'listing_title',
          category: 'listing',
          title: 'Promotional Terms in App Title',
          description: 'Google Play prohibits keywords like "Best", "Top #1", "Free" in the app title.',
          status: 'failed',
          recommendation: 'Remove promotional or superlative adjectives from the app title.',
        });
      }
    } else if (storeListing.title.length > 30) {
      items.push({
        id: 'listing_title',
        category: 'listing',
        title: 'App Title Exceeds 30 Characters',
        description: `Current length: ${storeListing.title.length} chars (Limit is 30 characters).`,
        status: 'failed',
        recommendation: 'Shorten your app title to 30 characters or fewer.',
      });
    }

    // 8. Short Description (Max 80 chars)
    if (storeListing.shortDescription.length > 0 && storeListing.shortDescription.length <= 80) {
      items.push({
        id: 'listing_short_desc',
        category: 'listing',
        title: 'Short Description Length (Valid)',
        description: `Short description is ${storeListing.shortDescription.length}/80 characters.`,
        status: 'passed',
        recommendation: 'Good length for mobile search listing preview.',
      });
    } else if (storeListing.shortDescription.length > 80) {
      items.push({
        id: 'listing_short_desc',
        category: 'listing',
        title: 'Short Description Exceeds 80 Characters',
        description: `Current length: ${storeListing.shortDescription.length} chars (Limit is 80).`,
        status: 'failed',
        recommendation: 'Reduce short description under 80 characters.',
      });
    }

    // Calculate score
    const passedCount = items.filter(i => i.status === 'passed').length;
    const scorePercent = Math.round((passedCount / Math.max(1, items.length)) * 100);

    return { items, scorePercent };
  }
}
